/**
 * Generates the race registry from the bundled datasets — the single source of truth for
 * which races exist.
 *
 *   npm run registry:generate   write src/lib/data/race-registry.generated.ts and data/index.json
 *   npm run registry:check      exit 1 if either file is missing or stale (also enforced by `npm test`)
 *
 * Every data/races/*.json file must parse, satisfy the race schema, and declare an `id` equal to
 * its filename (the route segment). Anything else fails generation with a message naming the
 * file; nothing invalid is ever registered. Output is sorted by id (code-point order), so it is
 * identical regardless of filesystem order, locale or platform. The data files themselves are
 * only read, never rewritten, so their dataset-version hashes are unaffected.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { raceSchema } from "../src/lib/data/schema";

export const RACES_DIR = path.join(process.cwd(), "data", "races");
export const MODULE_PATH = path.join(process.cwd(), "src", "lib", "data", "race-registry.generated.ts");
export const INDEX_PATH = path.join(process.cwd(), "data", "index.json");

const ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export interface RegistryEntry {
  id: string;
  file: string;
  season: number;
  round: number;
  raceName: string;
}

export type RegistryBuild =
  | { ok: true; entries: RegistryEntry[]; moduleSource: string; indexJson: string }
  | { ok: false; errors: string[] };

/**
 * Validate the datasets in `dir` and render the registry. Pure apart from reading `dir`;
 * `fileOrder` lets tests prove the result does not depend on directory listing order.
 */
export function buildRegistry(dir: string, fileOrder: (names: string[]) => string[] = (n) => n): RegistryBuild {
  const errors: string[] = [];
  let names: string[];
  try {
    names = fileOrder(readdirSync(dir));
  } catch (e) {
    return { ok: false, errors: [`cannot read ${dir}: ${(e as Error).message}`] };
  }

  const entries: RegistryEntry[] = [];
  const seenIds = new Map<string, string>();
  for (const file of names) {
    if (!file.endsWith(".json")) {
      errors.push(`${file}: unexpected file in data/races (only <race-id>.json files are allowed)`);
      continue;
    }
    const stem = file.slice(0, -".json".length);
    if (!ID_PATTERN.test(stem)) {
      errors.push(`${file}: filename must be a lowercase race id (a-z, 0-9, single hyphens), e.g. 2024-01-bahrain.json`);
      continue;
    }
    let raw: unknown;
    try {
      raw = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
    } catch (e) {
      errors.push(`${file}: invalid JSON (${(e as Error).message})`);
      continue;
    }
    const parsed = raceSchema.safeParse(raw);
    if (!parsed.success) {
      const issues = parsed.error.issues.slice(0, 5).map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`);
      errors.push(`${file}: fails the race schema — ${issues.join("; ")}${parsed.error.issues.length > 5 ? "; …" : ""}`);
      continue;
    }
    const race = parsed.data;
    if (race.id !== stem) {
      errors.push(`${file}: declares id "${race.id}" but its filename (and route) is "${stem}"`);
      continue;
    }
    const previous = seenIds.get(race.id);
    if (previous) {
      errors.push(`${file}: duplicate race id "${race.id}" (already declared by ${previous})`);
      continue;
    }
    seenIds.set(race.id, file);
    entries.push({ id: race.id, file, season: race.season, round: race.round, raceName: race.raceName });
  }

  if (errors.length === 0 && entries.length === 0) errors.push(`no race datasets found in ${dir}`);
  if (errors.length > 0) return { ok: false, errors };

  // Code-point order: independent of locale (unlike localeCompare) and of filesystem order.
  entries.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return { ok: true, entries, moduleSource: renderModule(entries), indexJson: renderIndex(entries) };
}

const identifier = (id: string) => `race_${id.replace(/-/g, "_")}`;

function renderModule(entries: RegistryEntry[]): string {
  const imports = entries.map((e) => `import ${identifier(e.id)} from "../../../data/races/${e.file}";`).join("\n");
  const ids = entries.map((e) => `  ${JSON.stringify(e.id)},`).join("\n");
  const files = entries.map((e) => `  ${JSON.stringify(e.id)}: ${identifier(e.id)},`).join("\n");
  return `// GENERATED by scripts/generate-race-registry.ts from data/races/*.json — do not edit by hand.
// Regenerate with \`npm run registry:generate\`; \`npm test\` fails if this file is stale.
${imports}

/** Every bundled race id, in code-point order. Each id equals its file name and the dataset's declared id. */
export const REGISTERED_RACE_IDS = [
${ids}
] as const;

export type RegisteredRaceId = (typeof REGISTERED_RACE_IDS)[number];

/** Raw dataset payloads keyed by race id; schema-validated by the repository on load. */
export const REGISTERED_RACE_FILES: Readonly<Record<RegisteredRaceId, unknown>> = {
${files}
};
`;
}

function renderIndex(entries: RegistryEntry[]): string {
  return JSON.stringify(entries.map(({ id, season, round, raceName }) => ({ id, season, round, raceName })), null, 2) + "\n";
}

function readOrNull(file: string): string | null {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return null;
  }
}

function main() {
  const check = process.argv.includes("--check");
  const build = buildRegistry(RACES_DIR);
  if (!build.ok) {
    console.error("✖ Race registry generation failed:");
    for (const e of build.errors) console.error(`    ${e}`);
    process.exit(1);
  }
  const outputs: [string, string][] = [
    [MODULE_PATH, build.moduleSource],
    [INDEX_PATH, build.indexJson],
  ];
  if (check) {
    const stale = outputs.filter(([file, content]) => readOrNull(file) !== content).map(([file]) => path.relative(process.cwd(), file));
    if (stale.length) {
      console.error(`✖ Race registry is stale: ${stale.join(", ")}. Run \`npm run registry:generate\`.`);
      process.exit(1);
    }
    console.log(`✔ Race registry is up to date (${build.entries.length} races).`);
    return;
  }
  for (const [file, content] of outputs) writeFileSync(file, content);
  console.log(`✔ Registered ${build.entries.length} races: ${build.entries.map((e) => e.id).join(", ")}`);
}

// Run only when executed directly (tests import buildRegistry without side effects).
if (/generate-race-registry\.ts$/.test(process.argv[1] ?? "")) main();
